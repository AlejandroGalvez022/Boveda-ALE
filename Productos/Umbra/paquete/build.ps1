# Umbra — build.
#
# There is no bundler and no Node here on purpose: the whole point of the
# product is that it has zero dependencies, and the build should match.
#
# src/umbra.js is the single source of truth (an ES module). This script
# produces the two files that ship:
#
#   dist/umbra.esm.js  — the module, verbatim.
#   dist/umbra.js      — the same code as a classic <script>, exposing
#                        window.Umbra and auto-initialising [data-umbra].
#
# Run:  powershell -ExecutionPolicy Bypass -File build.ps1

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$src  = Join-Path $root 'src\umbra.js'
$dist = Join-Path $root 'dist'

if (-not (Test-Path $src)) { throw "No encuentro el fuente: $src" }
if (-not (Test-Path $dist)) { New-Item -ItemType Directory -Path $dist | Out-Null }

$code = Get-Content $src -Raw

# --- ESM: tal cual ---------------------------------------------------------
Set-Content -Path (Join-Path $dist 'umbra.esm.js') -Value $code -Encoding utf8
Write-Host "  dist/umbra.esm.js" -ForegroundColor DarkGreen

# --- Classic <script> ------------------------------------------------------
# Se quita la linea de export y se envuelve en un IIFE para no ensuciar el
# ambito global con los ayudantes internos (parseColor, clamp, PRESETS...).
$body = [regex]::Replace($code, '(?m)^\s*export\s*\{[^}]*\}\s*;?\s*$', '')

$classic = @"
/*! UMBRA v1.0.0 — classic build. Generated from src/umbra.js by build.ps1.
    Do not edit this file: edit the source and build again. */
(function (root) {
"use strict";
$body
  root.Umbra = Umbra;
  root.Umbra.autoInit = autoInit;
  root.Umbra.presets  = PRESETS;

  // Auto-init anything already in the document, and anything added later
  // by a page builder (Webflow, Framer, Elementor) once it settles.
  function boot() { autoInit(); }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})(typeof window !== 'undefined' ? window : this);
"@

Set-Content -Path (Join-Path $dist 'umbra.js') -Value $classic -Encoding utf8
Write-Host "  dist/umbra.js" -ForegroundColor DarkGreen

$k1 = [Math]::Round((Get-Item (Join-Path $dist 'umbra.js')).Length / 1KB, 1)
$k2 = [Math]::Round((Get-Item (Join-Path $dist 'umbra.esm.js')).Length / 1KB, 1)
Write-Host ("`nHecho. umbra.js {0} KB | umbra.esm.js {1} KB" -f $k1, $k2) -ForegroundColor Green
