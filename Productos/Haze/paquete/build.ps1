# Lustre - build.
#
# No bundler and no Node, on purpose: the product promises zero dependencies,
# so its build should not need any either.
#
# src/lustre.js is the single source of truth (an ES module). This produces:
#   dist/lustre.esm.js      - the module, verbatim.
#   dist/lustre.js          - the same code as a classic <script>, exposing
#                           window.Lustre and auto-initialising [data-lustre].
#   dist/Lustre.framer.tsx  - src/framer.tsx with the engine inlined: one file
#                           a Framer user pastes into a new code file.
#
# Run:  powershell -ExecutionPolicy Bypass -File build.ps1
#
# ENCODING: every read and write goes through [IO.File] with UTF-8 (no BOM).
# Get-Content / Set-Content in PowerShell 5.1 read files without a BOM as
# ANSI, which turned every em dash in the comments into mojibake in dist/.
# This file itself stays ASCII-only for the same reason.

$ErrorActionPreference = 'Stop'
$root   = $PSScriptRoot
$src    = Join-Path $root 'src\lustre.js'
$framer = Join-Path $root 'src\framer.tsx'
$dist   = Join-Path $root 'dist'
$utf8   = New-Object System.Text.UTF8Encoding($false)

if (-not (Test-Path $src)) { throw "Source not found: $src" }
if (-not (Test-Path $dist)) { New-Item -ItemType Directory -Path $dist | Out-Null }

$code = [IO.File]::ReadAllText($src, $utf8)
$version = [regex]::Match($code, "Lustre\.version\s*=\s*'([^']+)'").Groups[1].Value

[IO.File]::WriteAllText((Join-Path $dist 'lustre.esm.js'), $code, $utf8)
Write-Host "  dist/lustre.esm.js" -ForegroundColor DarkGreen

# The export line goes, and the rest is wrapped in an IIFE so the internal
# helpers (parseColor, clamp, MOTIFS...) do not leak into the global scope.
$body = [regex]::Replace($code, '(?m)^\s*export\s*\{[^}]*\}\s*;?\s*$', '')

$classic = @"
/*! LUSTRE v$version - classic build. Generated from src/lustre.js by build.ps1.
    Do not edit this file: edit the source and build again. */
(function (root) {
"use strict";
$body
  root.Lustre = Lustre;
  root.Lustre.autoInit = autoInit;
  root.Lustre.palettes = PALETTES;

  function boot() { autoInit(); }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})(typeof window !== 'undefined' ? window : this);
"@
[IO.File]::WriteAllText((Join-Path $dist 'lustre.js'), $classic, $utf8)
Write-Host "  dist/lustre.js" -ForegroundColor DarkGreen

if (Test-Path $framer) {
  $tpl = [IO.File]::ReadAllText($framer, $utf8)
  if ($tpl.IndexOf('/*__LUSTRE_ENGINE__*/') -lt 0) { throw "src/framer.tsx has no /*__LUSTRE_ENGINE__*/ marker" }
  $out = $tpl.Replace('/*__LUSTRE_ENGINE__*/', $body.Trim())
  [IO.File]::WriteAllText((Join-Path $dist 'Lustre.framer.tsx'), $out, $utf8)
  Write-Host "  dist/Lustre.framer.tsx" -ForegroundColor DarkGreen
}

# Guard: a mis-decoded dash or arrow shows up as these two-byte sequences.
foreach ($f in Get-ChildItem $dist -File) {
  $t = [IO.File]::ReadAllText($f.FullName, $utf8)
  $bad = [regex]::Matches($t, [string][char]0x00E2 + '[' + [char]0x0080 + '-' + [char]0x20AC + ']').Count
  if ($bad -gt 0) { throw ("Encoding broken in " + $f.Name + ": " + $bad + " mojibake sequences") }
}

$k1 = [Math]::Round((Get-Item (Join-Path $dist 'lustre.js')).Length / 1KB, 1)
$k2 = [Math]::Round((Get-Item (Join-Path $dist 'lustre.esm.js')).Length / 1KB, 1)
Write-Host ("`nDone. lustre.js {0} KB | lustre.esm.js {1} KB" -f $k1, $k2) -ForegroundColor Green
