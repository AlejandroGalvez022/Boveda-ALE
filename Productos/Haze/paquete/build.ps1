# Haze — build.
#
# No bundler and no Node, on purpose: the product promises zero dependencies,
# so its build should not need any either.
#
# src/haze.js is the single source of truth (an ES module). This produces:
#   dist/haze.esm.js  — the module, verbatim.
#   dist/haze.js      — the same code as a classic <script>, exposing
#                       window.Haze and auto-initialising [data-haze].
#
# Run:  powershell -ExecutionPolicy Bypass -File build.ps1

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$src  = Join-Path $root 'src\haze.js'
$dist = Join-Path $root 'dist'

if (-not (Test-Path $src)) { throw "No encuentro el fuente: $src" }
if (-not (Test-Path $dist)) { New-Item -ItemType Directory -Path $dist | Out-Null }

$code = Get-Content $src -Raw

Set-Content -Path (Join-Path $dist 'haze.esm.js') -Value $code -Encoding utf8
Write-Host "  dist/haze.esm.js" -ForegroundColor DarkGreen

# Se quita la linea de export y se envuelve en un IIFE, para no dejar sueltos
# en el ambito global los ayudantes internos (parseColor, clamp, MOTIFS...).
$body = [regex]::Replace($code, '(?m)^\s*export\s*\{[^}]*\}\s*;?\s*$', '')

$classic = @"
/*! HAZE v1.0.0 — classic build. Generated from src/haze.js by build.ps1.
    Do not edit this file: edit the source and build again. */
(function (root) {
"use strict";
$body
  root.Haze = Haze;
  root.Haze.autoInit = autoInit;
  root.Haze.palettes = PALETTES;

  function boot() { autoInit(); }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})(typeof window !== 'undefined' ? window : this);
"@

Set-Content -Path (Join-Path $dist 'haze.js') -Value $classic -Encoding utf8
Write-Host "  dist/haze.js" -ForegroundColor DarkGreen

$k1 = [Math]::Round((Get-Item (Join-Path $dist 'haze.js')).Length / 1KB, 1)
$k2 = [Math]::Round((Get-Item (Join-Path $dist 'haze.esm.js')).Length / 1KB, 1)
Write-Host ("`nHecho. haze.js {0} KB | haze.esm.js {1} KB" -f $k1, $k2) -ForegroundColor Green
